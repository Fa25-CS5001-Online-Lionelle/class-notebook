def add_numbers(a: int | float, b: int | float) -> int | float:
    """
    Adds two numbers together.
    
    Examples:
    >>> add_numbers(1, 2)
    3
    >>> add_numbers(5, 7)
    12
    >>> add_numbers(-1, 1)
    0
    >>> add_numbers(5, 7.0)
    12.0
    
    Parameters:
        a (int): First number
        b (int): Second number
    
    Returns:
        int: Sum of a and b
    """
    return a + b 


